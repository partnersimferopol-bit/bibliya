def emit(name: str, category: str, prefix: str, items: list) -> None:
    lines = [
        'import type { BibleQuestion } from "@/types";',
        "",
        f"export const {name}: BibleQuestion[] = [",
    ]
    for i, t in enumerate(items, 1):
        q, a, b, c, d, correct, diff, expl = t
        lines.append("  {")
        lines.append(f'    id: "{prefix}-{i}",')
        lines.append(f'    category: "{category}",')
        lines.append(f"    question: {json_str(q)},")
        lines.append("    options: {")
        lines.append(f'      A: {json_str(a)}, B: {json_str(b)}, C: {json_str(c)}, D: {json_str(d)},')
        lines.append("    },")
        lines.append(f'    correctAnswer: "{correct}",')
        lines.append(f'    difficulty: "{diff}",')
        lines.append(f"    explanation: {json_str(expl)},")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    (OUT / f"{file_map[name]}.ts").write_text("\n".join(lines), encoding="utf-8")


def json_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


